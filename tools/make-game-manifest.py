"""Record metadata for a locally supplied, supported NFS Underground Xbox disc."""
import argparse
import hashlib
import json
from pathlib import Path
from inspect_game import inspect, ROOT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("game", type=Path)
    args = parser.parse_args()
    result = inspect(args.game)
    if not result["ok"] or result["kind"] != "extracted_disc":
        parser.error("A supported extracted disc is required")
    directories = ("CARS", "FRONTEND", "GLOBAL", "LANGUAGES", "MEMCARD", "MOVIES", "SOUND", "TRACKS")
    files = [args.game / "default.xbe"]
    for directory in directories:
        folder = args.game / directory
        if not folder.is_dir():
            parser.error(f"Missing disc directory: {directory}")
        files.extend(sorted(p for p in folder.rglob("*") if p.is_file()))
    entries = []
    for path in files:
        with path.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        entries.append(dict(path=path.relative_to(args.game).as_posix(), bytes=path.stat().st_size, sha256=digest))
    (ROOT / "config/game-manifest.json").write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")
    java = 'package org.nfsu1.quest;\n\n/** Disc metadata only; generated by tools/make-game-manifest.py. */\nfinal class GameManifest {\n    static final GameDataImporter.Expected[] FILES = {\n'
    java += "".join(f'        new GameDataImporter.Expected("{e["path"]}", {e["bytes"]}L, "{e["sha256"]}"),\n' for e in entries)
    java += '    };\n    private GameManifest() {}\n}\n'
    (ROOT / "quest/app/src/main/java/org/nfsu1/quest/GameManifest.java").write_text(java, encoding="utf-8")
    print(f"Recorded {len(entries)} files, {sum(e['bytes'] for e in entries):,} bytes; no game contents copied.")


if __name__ == "__main__":
    main()
